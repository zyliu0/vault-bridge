# v16.6.0 (Batch C7) — module-level extraction error registry.
#
# Pre-v16.6 the built-in handlers (PDF, DOCX, PPTX, XLSX) caught every
# library exception and returned ``""``, indistinguishable from a
# legitimately empty file. The 2026-05-04 SSS field report flagged a
# 1-byte-truncated XLSX whose ``BadZipFile`` was masked as
# ``no_content`` — the user could not tell whether the file was
# corrupt, password-protected, or genuinely blank. This registry
# stashes the most recent extraction error per file path so
# ``read_text_with_status`` can surface it. Path-keyed (not thread-
# safe globally — intended for the single-process scan pipeline only).
_EXTRACTION_ERRORS: Dict[str, str] = {}


def _record_extraction_error(path: str, library: str, exc: BaseException) -> None:
    msg = f"{library}: {type(exc).__name__}: {exc}"
    _EXTRACTION_ERRORS[str(path)] = msg


def consume_extraction_error(path: str) -> Optional[str]:
    """Return any recorded extraction error for ``path`` and clear it.

    v16.6.0 (Batch C7). Used by ``read_text_with_status`` to recover
    library exceptions that the built-in handlers swallowed. The
    registry is path-keyed and consumed-on-read so a clean follow-up
    extraction does not see stale errors.
    """
    return _EXTRACTION_ERRORS.pop(str(path), None)


def _pdf_read_text(path: str) -> str:
    """Extract text from a PDF.

    v16.7.0 (TLS Bug 1+5): cascade through pdfplumber → PyMuPDF (fitz)
    → pdfminer.six → PyPDF2 → OCR. Pre-v16.7 the built-in dispatch was
    PyPDF2-only, which produces 4 KB of CMap garbage like
    ``OOb?WÎNa^ú¾èOá`oQl_…`` on Chinese PDFs that use ``/UniGB-UTF16-H``,
    ``/UniCNS-UTF16-H``, or other CID-keyed fonts. The 2026-05-04 TLS
    field report confirmed pdfplumber/fitz/pdfminer all produce clean
    text on the same files; this rewrite makes them the preferred path.

    Design notes:
      * pdfplumber goes first because it handles CJK glyph layout
        better than fitz (per-glyph stripping is acceptable; the
        garble gate later filters the result if extraction quality
        is too low).
      * fitz is second — fast, full Adobe-GB1 / Adobe-Japan1 support.
      * pdfminer.high_level.extract_text is the third try; it is the
        same engine pdfplumber wraps but with different defaults so
        worth retrying when pdfplumber's layout pass mangled glyphs.
      * PyPDF2 stays as a low-priority fallback for back-compat.
        PyPDF2's ``warnings.warn`` calls (``Advanced encoding /UniGB-
        UTF16-H not implemented yet``) are now captured and surfaced
        through the extraction-error registry so they no longer
        disappear into stderr.
      * OCR via pytesseract over PyMuPDF page renders is the final
        fallback for scanned PDFs (v16.5.0, Fix F).

    Each extractor's exception goes through ``_record_extraction_error``
    so ``read_text_with_status`` can surface it as a warning instead of
    silently returning ``""``.
    """
    # v16.13.0 (JAE Finding 0): each extractor's output goes through
    # the CMap-garble gate before being accepted. Pre-v16.13 the
    # cascade returned the first non-empty result, so a CMap-broken
    # pdfminer extract (PUA-saturated unicode soup) short-circuited
    # the entire cascade — the user got 25KB of unreadable text tagged
    # ``content_confidence: high``. The gate forces fall-through to
    # the next extractor when the result is detectably broken.
    import validate_body as _vb

    # 1. pdfplumber — best layout-aware CJK support via pdfminer.six.
    try:
        import pdfplumber  # type: ignore
        with pdfplumber.open(path) as pdf:
            parts = [
                (p.extract_text() or "")
                for p in pdf.pages[:200]
            ]
        text = "\n\n".join(s for s in parts if s.strip())
        if text.strip() and not _vb.is_cmap_garbled_pdf(text):
            return text
    except Exception as exc:
        _record_extraction_error(path, "pdfplumber", exc)
        logger.debug("pdfplumber failed for %s: %s", path, exc)

    # 2. PyMuPDF (fitz) — fast, full Adobe-GB1 support.
    try:
        import fitz  # type: ignore
        doc = fitz.open(path)
        try:
            n = min(len(doc), 200)
            parts = [doc.load_page(i).get_text() for i in range(n)]
        finally:
            doc.close()
        text = "\n\n".join(s for s in parts if s.strip())
        if text.strip() and not _vb.is_cmap_garbled_pdf(text):
            return text
    except Exception as exc:
        _record_extraction_error(path, "PyMuPDF", exc)
        logger.debug("fitz failed for %s: %s", path, exc)

    # 3. pdfminer.six high-level — same engine pdfplumber wraps but
    # with different defaults; sometimes succeeds where pdfplumber's
    # layout pass mangled glyphs.
    try:
        from pdfminer.high_level import extract_text as _pdfminer_text  # type: ignore
        text = _pdfminer_text(path, maxpages=200) or ""
        if text.strip() and not _vb.is_cmap_garbled_pdf(text):
            return text
    except Exception as exc:
        _record_extraction_error(path, "pdfminer.six", exc)
        logger.debug("pdfminer.six failed for %s: %s", path, exc)

    # 4. PyPDF2 — last text extractor (kept for compatibility). Capture
    # any ``warnings.warn`` output (e.g. CMap-not-supported diagnostics)
    # so the extraction-error registry sees them; pre-v16.7 these
    # warnings disappeared into stderr (TLS Bug 5).
    pypdf_text = ""
    pypdf_warnings: List[str] = []
    import warnings as _warnings
    try:
        import PyPDF2  # type: ignore
    except Exception as exc:
        _record_extraction_error(path, "PyPDF2", exc)
        return _pdf_ocr_fallback(path) or ""

    with _warnings.catch_warnings(record=True) as captured:
        _warnings.simplefilter("always")
        try:
            reader = PyPDF2.PdfReader(path)
            parts2: List[str] = []
            for page in reader.pages:
                try:
                    t = page.extract_text()
                    if t:
                        parts2.append(t)
                except Exception:
                    pass
            pypdf_text = "\n".join(parts2).strip()
        except Exception as exc:
            _record_extraction_error(path, "PyPDF2", exc)
            logger.debug("PyPDF2 failed for %s: %s", path, exc)
        for w in captured or []:
            msg = str(w.message)
            pypdf_warnings.append(msg)
            # CJK-CMap diagnostic — surface as a real error so the
            # user knows to install pdfplumber/PyMuPDF for this PDF.
            if (
                "Advanced encoding /Uni" in msg
                or "/UniGB" in msg
                or "/UniCNS" in msg
                or "/UniJIS" in msg
                or "/UniKS" in msg
                or "/Adobe-GB1" in msg
                or "/Adobe-Japan1" in msg
            ):
                _record_extraction_error(
                    path, "PyPDF2",
                    RuntimeError(
                        "CJK CMap not supported by PyPDF2: "
                        + msg
                        + ". Install pdfplumber or PyMuPDF for clean text."
                    ),
                )
                # Drop PyPDF2's CMap-decoded garbage on the floor —
                # pdfplumber already failed, but garbage is worse than
                # nothing because the garble gate downstream may miss
                # short outputs.
                pypdf_text = ""

    # v16.13.0 (JAE Finding 0): even after PyPDF2's own CMap warnings
    # are checked above, the returned bytes can still be PUA garbage
    # if the CMap was partially resolved. Final gate before accepting.
    if len(pypdf_text) >= 50 and not _vb.is_cmap_garbled_pdf(pypdf_text):
        return pypdf_text

    # 5. OCR via pytesseract over PyMuPDF page renders (Fix F).
    ocr_text = _pdf_ocr_fallback(path)
    if ocr_text:
        return ocr_text
    # Last resort: return whatever PyPDF2 produced (may be empty or
    # short) so callers can decide.
    return pypdf_text  # may be empty


def _pdf_ocr_fallback(path: str) -> str:
    """Run pytesseract over PDF page renders.

    Returns ``""`` if pytesseract or PyMuPDF are unavailable, or if the
    OCR pass produces nothing usable. Never raises.

    OCR is expensive (Tesseract is ~1-3 seconds per page); we cap at
    the first 5 pages so a 200-page scan doesn't dominate the scan
    runtime. Most scanned-PDF events the user cares about have their
    headline content on the first 1-3 pages anyway.
    """
    try:
        import pytesseract  # type: ignore
        from PIL import Image  # type: ignore
    except ImportError:
        return ""
    try:
        import fitz  # type: ignore  # PyMuPDF
    except ImportError:
        return ""

    parts: List[str] = []
    try:
        doc = fitz.open(path)
        try:
            n_pages = min(len(doc), 5)
            for page_idx in range(n_pages):
                try:
                    page = doc[page_idx]
                    pix = page.get_pixmap(dpi=200)
                    img = Image.frombytes(
                        "RGB", (pix.width, pix.height), pix.samples,
                    )
                    text = pytesseract.image_to_string(img)
                    if text and text.strip():
                        parts.append(f"--- page {page_idx + 1} ---\n{text.strip()}")
                except Exception as exc:
                    logger.debug(
                        "OCR page %d failed for %s: %s",
                        page_idx, path, exc,
                    )
        finally:
            doc.close()
    except Exception as exc:
        logger.debug("OCR fallback failed for %s: %s", path, exc)
        return ""
    return "\n\n".join(parts)


def _docx_read_text(path: str) -> str:
    """Extract text from a DOCX using python-docx. Returns '' on any failure.

    v16.6.0 (Batch C7): record corrupt-file exceptions (BadZipFile,
    KeyError, PackageNotFoundError) so ``read_text_with_status`` can
    surface the real cause to the scan pipeline.
    """
    try:
        from docx import Document  # type: ignore
        doc = Document(path)
        return "\n".join(p.text for p in doc.paragraphs if p.text)
    except Exception as exc:
        _record_extraction_error(path, "python-docx", exc)
        logger.debug("DOCX text extraction failed for %s: %s", path, exc)
        return ""


def _xlsx_read_text(path: str) -> str:
    """Extract text from an XLSX using openpyxl.

    v16.4.0 (AUDIT-1b) — pre-v16.4 ``_extract_text_office`` returned
    ``""`` for xlsx, which combined with the empty image extractor
    in ``extract_embedded_images`` produced 0 bytes / 0 images for
    every spreadsheet. The audit's representative XLSX (`220928
    exhibition size.xlsx`) has 1.2 KB of legitimate content (a
    component-size table) plus 40 inline images — none of which
    landed in any note. openpyxl reads the cell grid; the per-cell
    text is concatenated tab-separated per row, with one
    ``# {sheet_name}`` heading per worksheet.
    """
    try:
        import openpyxl  # type: ignore
        wb = openpyxl.load_workbook(path, data_only=True, read_only=True)
        parts: List[str] = []
        for sheet in wb.worksheets:
            parts.append(f"# {sheet.title}")
            for row in sheet.iter_rows(values_only=True):
                # Drop trailing all-empty cells but preserve interior
                # blanks so column alignment stays meaningful.
                cells = [
                    "" if v is None else str(v)
                    for v in row
                ]
                while cells and cells[-1] == "":
                    cells.pop()
                if cells:
                    parts.append("\t".join(cells))
            parts.append("")  # blank line between sheets
        try:
            wb.close()
        except Exception:
            pass
        return "\n".join(parts).strip()
    except Exception as exc:
        # v16.6.0 (Batch C7): the SSS field report's truncated XLSX
        # raised BadZipFile here; pre-v16.6 the message vanished.
        _record_extraction_error(path, "openpyxl", exc)
        logger.debug("XLSX text extraction failed for %s: %s", path, exc)
        return ""


def _pptx_read_text(path: str) -> str:
    """Extract text from a PPTX using python-pptx. Returns '' on any failure.

    v16.6.0 (Batch C7): record corrupt-zip / parse exceptions in the
    extraction-error registry.
    """
    try:
        from pptx import Presentation  # type: ignore
        prs = Presentation(path)
        parts: List[str] = []
        for slide in prs.slides:
            for shape in slide.shapes:
                if hasattr(shape, "text") and shape.text:
                    parts.append(shape.text)
        return "\n".join(parts)
    except Exception as exc:
        _record_extraction_error(path, "python-pptx", exc)
        logger.debug("PPTX text extraction failed for %s: %s", path, exc)
        return ""


def _plain_read_text(path: str) -> str:
    """Read a plain-text file. Returns '' on any failure.

    v16.4.0 (AUDIT-4): for ``.rtf`` files, runs the bytes through
    ``striprtf`` to get unformatted text. striprtf is a tiny pure-Python
    package; if it's absent we fall back to soffice headless and finally
    to a literal byte read (which gives the user RTF source, not ideal
    but better than ``""``).
    """
    p = Path(path)
    ext = p.suffix.lstrip(".").lower()
    if ext == "rtf":
        return _rtf_read_text(path)
    try:
        return p.read_text(encoding="utf-8", errors="replace")
    except Exception as exc:
        logger.debug("Plain text read failed for %s: %s", path, exc)
        return ""


def _rtf_read_text(path: str) -> str:
    """Extract text from an RTF document.

    Pipeline: striprtf → soffice headless → literal-bytes fallback.
    Never raises.
    """
    # 1. striprtf is the lightweight pure-Python path.
    try:
        from striprtf.striprtf import rtf_to_text  # type: ignore
        raw = Path(path).read_text(encoding="utf-8", errors="replace")
        out = rtf_to_text(raw)
        if out and out.strip():
            return out
    except ImportError:
        pass
    except Exception as exc:
        logger.debug("striprtf failed for %s: %s", path, exc)

    # 2. LibreOffice headless fallback — works without striprtf.
    text = _soffice_convert_to_txt(path)
    if text:
        return text

    # 3. Last resort — return the raw bytes so the user sees RTF source
    # rather than a silent skip. The garbled-extract gate in scan_pipeline
    # will likely flag it; that's the right signal that a striprtf install
    # is needed.
    try:
        return Path(path).read_text(encoding="utf-8", errors="replace")
    except Exception:
        return ""


def _soffice_convert_to_txt(path: str) -> str:
    """Shell out to LibreOffice headless and return the converted text.

    Used as a shared fallback for RTF (and could be reused for other
    plain-but-tricky formats). Returns '' on any failure.
    """
    import shutil as _shutil
    import subprocess as _sp
    import tempfile as _tf
    binaries = ("soffice", "libreoffice")
    macos_apps = ("/Applications/LibreOffice.app/Contents/MacOS/soffice",)
    exe = ""
    for name in binaries:
        found = _shutil.which(name)
        if found:
            exe = found
            break
    if not exe:
        for app in macos_apps:
            if Path(app).exists():
                exe = app
                break
    if not exe:
        return ""
    with _tf.TemporaryDirectory() as td:
        try:
            proc = _sp.run(
                [exe, "--headless", "--convert-to", "txt", "--outdir", td, path],
                capture_output=True, timeout=60, check=False,
            )
        except Exception as exc:
            logger.debug("soffice convert failed for %s: %s", path, exc)
            return ""
        if proc.returncode != 0:
            return ""
        out_file = Path(td) / f"{Path(path).stem}.txt"
        if not out_file.exists():
            return ""
        try:
            return out_file.read_text(encoding="utf-8", errors="replace")
        except Exception:
            return ""


# ---------------------------------------------------------------------------
# Dispatch tables (v14.8 unification)
# ---------------------------------------------------------------------------
#
# Before v14.8, read_text() and extract_images() were long if/elif chains on
# `cfg.category`. Adding a new category required editing both chains AND
# the registry AND (for delegated types) the handler_dispatcher module.
#
# Now the dispatch is table-driven. Each category has two entries:
#
#   _TEXT_DISPATCH[category] = (needs_ext: bool, fn)
#     fn(path, workdir, ext) -> str — same signature regardless of needs
#     When not needs_ext, `ext` is ignored.
#
#   _IMAGE_DISPATCH[category] = fn
#     fn(path, workdir, ext) -> List[Path] — same uniform signature.
#
# Adding a new category is one entry in each table. Categories that should
# fall through to `handler_dispatcher` (CAD, vector-ai, raster-psd, etc.)
# do NOT need entries — they are handled by the default branch that checks
# `handler_dispatcher.is_delegated`.


def _extract_text_pdf(path, workdir, ext): return _pdf_read_text(path)
def _extract_text_plain(path, workdir, ext): return _plain_read_text(path)


def _extract_text_office(path, workdir, ext):
    if ext in ("docx", "doc"):
        return _docx_read_text(path)
    if ext in ("pptx", "ppt"):
        return _pptx_read_text(path)
    if ext == "xlsx":
        # v16.4.0 (AUDIT-1b) — wire openpyxl-based xlsx text extraction.
        return _xlsx_read_text(path)
    # xls handled via legacy spreadsheet path / soffice fallback.
    return ""


def _extract_images_passthrough(path, workdir, ext):
    return [Path(path)]


def _extract_images_container(path, workdir, ext):
    return _delegate_extract_images(Path(path), ext)


_TEXT_DISPATCH = {
    "document-pdf": _extract_text_pdf,
    "document-office": _extract_text_office,
    "text-plain": _extract_text_plain,
}


_IMAGE_DISPATCH = {
    "image-raster": _extract_images_passthrough,
    "image-vector": _extract_images_passthrough,
    "document-pdf": _extract_images_container,
    "document-office": _extract_images_container,
}


def _delegate_extract_images(src_path: Path, file_type: str) -> List[Path]:
    """Delegate to extract_embedded_images.extract for container types."""
    try:
        import extract_embedded_images  # type: ignore
        out_dir = src_path.parent / f"_extracted_{src_path.stem}"
        return extract_embedded_images.extract(src_path, out_dir, file_type)
    except Exception as exc:
        logger.debug("extract_embedded_images failed for %s: %s", src_path, exc)
        return []


def read_text(path: str, workdir: Optional[str] = None) -> str:
    """Extract text from `path` according to its file type.

    Looks up the category via `get_handler()`, then dispatches via
    `_TEXT_DISPATCH`. Unknown categories that are declared delegated
    (CAD, legacy Office, etc.) go to `handler_dispatcher`, which loads
    the per-extension module from `<workdir>/.vault-bridge/handlers/`.
    Everything else returns '' without raising.
    """
    cfg = get_handler(path)
    if cfg is None or not cfg.extract_text:
        return ""

    p = Path(path)
    if not p.exists():
        return ""

    ext = p.suffix.lstrip(".").lower()

    fn = _TEXT_DISPATCH.get(cfg.category)
    if fn is not None:
        return fn(path, workdir, ext)
    if handler_dispatcher.is_delegated(cfg.category):
        return handler_dispatcher.read_text(workdir, cfg.category, path)
    return ""


def read_text_with_status(
    path: str, workdir: Optional[str] = None,
) -> "tuple[str, Optional[str]]":
    """Extract text from `path`; return ``(text, error_msg)``.

    v16.5.0 (Fix A) — distinguishes "handler ran cleanly and produced
    nothing" from "handler raised". Pre-v16.5 the silent-swallow at
    handler-dispatch layer hid corrupt-file failures (BadZipFile,
    odafc binary missing, etc.). Returning the error string lets
    ``scan_pipeline`` surface the real cause to the user.

    Implementation: wraps ``read_text(path, workdir)`` with a try/except
    so test fixtures that mock ``read_text`` still fire. For the
    delegated path we also consult ``handler_dispatcher.read_text_with_status``
    to recover the underlying handler exception when ``read_text``
    swallowed it.
    """
    cfg = get_handler(path)
    if cfg is None or not cfg.extract_text:
        return "", None
    p = Path(path)
    if not p.exists():
        return "", None
    # Clear any prior extraction error before running so we don't
    # surface a stale message from an unrelated previous probe.
    consume_extraction_error(path)
    try:
        text = read_text(path, workdir=workdir)
    except Exception as exc:
        return "", f"{type(exc).__name__}: {exc}"
    # v16.6.0 (Batch C7): even when text is non-empty we expose any
    # recorded library exception (e.g. PDF that yielded text from
    # page 1 then PyPDF2 raised on page 2). Empty + recorded error is
    # the corrupt-file case.
    recorded = consume_extraction_error(path)
    if text:
        return text, recorded
    if recorded:
        return "", recorded
    # Empty result — for delegated categories, ask the dispatcher's
    # status-aware variant whether the handler raised. For built-in
    # categories an empty result is genuinely "nothing to extract".
    if handler_dispatcher.is_delegated(cfg.category):
        _, err = handler_dispatcher.read_text_with_status(
            workdir, cfg.category, path,
        )
        return "", err
    return "", None


def extract_images(path: str, workdir: Optional[str] = None) -> List[Path]:
    """Return the images for `path` according to its file type.

    Same dispatch shape as `read_text`: `_IMAGE_DISPATCH` handles the
    core categories; delegated categories (CAD, vector-ai, raster-psd,
    legacy-office, 3dm) go through `handler_dispatcher` so the
    per-extension workdir handler can render pages.
    """
    cfg = get_handler(path)
    if cfg is None or not cfg.extract_images:
        return []

    p = Path(path)
    if not p.exists():
        return []

    ext = p.suffix.lstrip(".").lower()

    fn = _IMAGE_DISPATCH.get(cfg.category)
    if fn is not None:
        return fn(path, workdir, ext)
    if handler_dispatcher.is_delegated(cfg.category):
        return handler_dispatcher.extract_images(workdir, cfg.category, path)
    return []


def extract_images_with_status(
    path: str, workdir: Optional[str] = None,
) -> "tuple[List[Path], Optional[str]]":
    """Same as :func:`extract_images`; also returns an error string when
    the handler raised. v16.5.0 (Fix A).

    Wraps ``extract_images(path, workdir)`` with a try/except so test
    fixtures that mock ``extract_images`` still fire correctly. For
    delegated categories we additionally consult the dispatcher's
    status-aware variant on empty results to recover errors that the
    inner handler swallowed.
    """
    cfg = get_handler(path)
    if cfg is None or not cfg.extract_images:
        return [], None
    p = Path(path)
    if not p.exists():
        return [], None
    try:
        paths = extract_images(path, workdir=workdir)
    except Exception as exc:
        return [], f"{type(exc).__name__}: {exc}"
    if paths:
        return list(paths), None
    if handler_dispatcher.is_delegated(cfg.category):
        _, err = handler_dispatcher.extract_images_with_status(
            workdir, cfg.category, path,
        )
        return [], err
    return [], None


def handle(path: str, workdir: Optional[str] = None) -> HandlerResult:
    """Process a file and return a HandlerResult.

    For known extensions:
      - Calls read_text() if extract_text is True, else sets text=''.
      - Calls extract_images() if extract_images is True, else sets images=[].
      - skipped=False, category=cfg.category.

    For unknown/empty/no-extension paths:
      - Returns HandlerResult(text=None, images=[], skipped=True, category='unknown').

    `workdir` is forwarded to read_text/extract_images so delegated
    categories (CAD, legacy Office) can dispatch to the per-extension
    handler modules under `<workdir>/.vault-bridge/handlers/`.

    Never raises.
    """
    cfg = get_handler(path)
    if cfg is None:
        return HandlerResult(text=None, images=[], skipped=True, category="unknown")

    try:
        text = read_text(path, workdir=workdir) if cfg.extract_text else ""
        images = extract_images(path, workdir=workdir) if cfg.extract_images else []
    except Exception as exc:
        logger.warning("handle() error processing %s: %s", path, exc)
        text = ""
        images = []

    return HandlerResult(
        text=text,
        images=images,
        skipped=False,
        category=cfg.category,
    )
