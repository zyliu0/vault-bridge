# Public API
# ---------------------------------------------------------------------------

def get_handler(path: str) -> Optional[HandlerConfig]:
    """Return the HandlerConfig for the given file path, or None if unrecognised.

    Lookup is by the last extension only (.tar.gz → 'gz').
    Case-insensitive. Leading dot removed.
    Returns None for empty paths, paths with no extension, and dot-files
    with no real extension (e.g. '.hidden').

    v16.6.0 (Batch C8): the registry lookup itself is the validity
    gate — folder basenames like ``210127 v2.3 工地照明 CD`` have a
    last-segment ``rsplit(".", 1)`` of "3 工地照明 CD" which is
    correctly NOT in HANDLERS and therefore returns None. The
    pre-v16.6 issue was that scan-pipeline callers built their own
    ext via naive string-splitting and tried to register it; now the
    canonical check is here. Folder-vs-file dispatch still happens
    in :func:`scan_pipeline.process_file` via ``Path.is_dir()``.

    Args:
        path: File path as string (may be relative or absolute).

    Returns:
        HandlerConfig or None.
    """
    if not path:
        return None

    p = Path(path)
    suffix = p.suffix  # '' or '.ext'
    if not suffix:
        return None

    ext = suffix.lstrip(".").lower()
    if not ext:
        # Dot-file like '.hidden' — suffix is '.hidden', ext is 'hidden'
        # But Path('.hidden').suffix == '' on Python 3.9, so this branch is
        # actually unreachable for dot-files.  Left for clarity.
        return None

    # v16.6.0 (Batch C8): reject "extensions" that don't look like
    # real ones — too long, contain whitespace, contain non-alnum.
    # ``210127 v2.3 工地照明 CD`` would otherwise turn into
    # ext="3 工地照明 cd" which passes ``HANDLERS.get`` (returning
    # None) but pollutes downstream logs as if it were a real ext.
    if not _looks_like_extension(ext):
        return None

    # Dot-file guard: Path('.hidden').stem == '.hidden', .suffix == ''
    # So we only reach here with a real extension.
    return HANDLERS.get(ext)


_EXT_RE = re.compile(r"^[a-z0-9]{1,6}$")


def _looks_like_extension(ext: str) -> bool:
    """Return True when ``ext`` is short, alphanumeric, plausibly a
    file extension. False for free-text-after-dot like
    "3 工地照明 cd". v16.6.0 (Batch C8)."""
    return bool(_EXT_RE.match(ext))


